(() => {
  'use strict';
  const shell = document.getElementById('elden-shell');
  const pages = [...shell.querySelectorAll('.elden-page')];
  const nav = [...shell.querySelectorAll('[data-elden-page]')];
  const detail = document.getElementById('elden-character-detail-content');
  const back = document.getElementById('elden-character-back');
  let lastCharacter = null;

  function element(tag, className, text) {
    const node = document.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined) node.textContent = text;
    return node;
  }
  function focusTitle(node) {
    if (!node) return;
    node.tabIndex = -1;
    node.focus({ preventScroll: true });
  }
  function setActive(id) {
    pages.forEach(page => {
      const active = page.id === `elden-${id}`;
      page.hidden = !active;
      page.classList.toggle('active', active);
    });
    nav.forEach(button => {
      const active = button.dataset.eldenPage === (id === 'character-detail' ? 'characters' : id);
      button.classList.toggle('active', active);
      if (active) button.setAttribute('aria-current', 'page');
      else button.removeAttribute('aria-current');
    });
  }
  function route(path, replace = false) {
    const hash = `#/elden/${path}`;
    if (location.hash !== hash) history[replace ? 'replaceState' : 'pushState'](null, '', hash);
    window.scrollTo({ top: 0, left: 0, behavior: 'auto' });
  }
  function showPage(id, { replace = false, focus = true } = {}) {
    if (currentChronicle !== 'elden') return;
    if (!['premise', 'characters'].includes(id)) id = 'premise';
    setActive(id);
    route(id, replace);
    if (focus) focusTitle(document.getElementById(`elden-${id}`).querySelector('h1, h2'));
  }
  function makeCard(character) {
    return window.CharacterPresentation.card(character, openCharacter);
  }
  function renderCharacter(character) {
    detail.replaceChildren(window.CharacterPresentation.profile(character, 'Beyond the Frenzied Flame', { holyTransformation: true }));
    window.ChronicleTools?.updateCharacterNavigation('elden', character);
  }
  function openCharacter(character, { replace = false } = {}) {
    if (currentChronicle !== 'elden' || !ELDEN_DATA.characters.includes(character)) return;
    lastCharacter = character;
    setActive('character-detail');
    renderCharacter(character);
    route(`character-${character.slug}`, replace);
    focusTitle(detail.querySelector('h2'));
  }
  ELDEN_DATA.characters.forEach(character => document.getElementById('elden-character-grid').appendChild(makeCard(character)));
  const pending = document.getElementById('elden-pending-grid');
  const pendingCount = Math.max(0, ELDEN_DATA.totalPlayers - ELDEN_DATA.characters.length);
  document.getElementById('elden-pending-label').textContent = pendingCount === 0 ? 'All seven characters added' : `${pendingCount === 1 ? 'One character' : pendingCount + ' characters'} still to be added`;
  pending.parentElement.hidden = pendingCount === 0;
  for (let i = ELDEN_DATA.characters.length; i < ELDEN_DATA.totalPlayers; i++) {
    const slot = element('div', 'elden-pending-slot');
    slot.setAttribute('aria-label', `Character slot ${i + 1}, to be added`);
    const mark = element('span', 'elden-pending-mark', '◇');
    mark.setAttribute('aria-hidden', 'true');
    slot.append(mark, element('span', '', 'To be added'));
    pending.appendChild(slot);
  }
  nav.forEach(button => button.addEventListener('click', () => showPage(button.dataset.eldenPage)));
  back.addEventListener('click', () => {
    showPage('characters', { replace: true, focus: false });
    if (lastCharacter) requestAnimationFrame(() => {
      const card = shell.querySelector(`[data-character="${lastCharacter.slug}"]`);
      card?.scrollIntoView({ block: 'center', behavior: 'auto' });
      card?.focus({ preventScroll: true });
    });
  });
  window.EldenChronicle = {
    characters: ELDEN_DATA.characters, premise: ELDEN_DATA.premise, shell, detail, showPage, openCharacter,
    enter() { showPage('premise', { replace: true }); },
    renderFromHash(hash) {
      const path = hash.startsWith('elden/') ? hash.slice(6) : 'premise';
      if (path.startsWith('character-')) {
        const character = ELDEN_DATA.characters.find(person => person.slug === path.slice(10));
        if (character) { openCharacter(character, { replace: true }); return; }
      }
      showPage(path, { replace: true });
    }
  };
})();
